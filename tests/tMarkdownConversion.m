classdef tMarkdownConversion < matlab.unittest.TestCase
    %TMARKDOWNCONVERSION Tests for local Markdown conversion.

    methods ( Test )

        function tConvertsGitHubFlavoredMarkdown( testCase )

            markdown = strjoin( [ ...
                "# GFM"; ...
                ""; ...
                "| A | B |"; ...
                "| --- | --- |"; ...
                "| 1 | 2 |"; ...
                ""; ...
                "~~deleted~~"; ...
                ""; ...
                "- [ ] pending"; ...
                ""; ...
                "```matlab"; ...
                "x = magic( 5 )"; ...
                "```" ], newline );
            doc = docmaker.md2xml( markdown );

            testCase.verifyEqual( ...
                doc.getElementsByTagName( "table" ).getLength(), 1 )
            testCase.verifyEqual( ...
                doc.getElementsByTagName( "del" ).getLength(), 1 )
            testCase.verifyEqual( ...
                doc.getElementsByTagName( "input" ).getLength(), 1 )

            pre = doc.getElementsByTagName( "pre" ).item( 0 );
            testCase.verifyEqual( ...
                string( pre.getParentNode().getAttribute( "class" ) ), ...
                "highlight highlight-source-matlab" )
            testCase.verifyEqual( ...
                string( pre.TextContent ), "x = magic( 5 )" )

        end % tConvertsGitHubFlavoredMarkdown

        function tConvertsImageMarkdownFixture( testCase )

            testsFolder = fileparts( mfilename( "fullpath" ) );
            markdownFile = fullfile( testsFolder, "ImageTest.md" );
            markdown = string( fileread( markdownFile ) );
            doc = docmaker.md2xml( markdown );

            img = doc.getElementsByTagName( "img" ).item( 0 );
            testCase.verifyEqual( ...
                string( img.getAttribute( "src" ) ), "ImageTest.png" )
            testCase.verifyEqual( ...
                string( img.getAttribute( "alt" ) ), "Cluster State" )

        end % tConvertsImageMarkdownFixture

    end % methods ( Test )

end % classdef